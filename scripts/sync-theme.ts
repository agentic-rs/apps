import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { hostRoot } from '../shared/scripts/paths';

// Use one committed source revision so unrelated host work never enters the platform theme snapshot.
const host_root = hostRoot();
const revision = execFileSync('git', ['-C', host_root, 'rev-parse', 'HEAD'], {
  encoding: 'utf8',
}).trim();
function source(path: string): string {
  return execFileSync('git', ['-C', host_root, 'show', `${revision}:${path}`], {
    encoding: 'utf8',
  });
}
function tokens(block: string): string {
  const declarations = [...block.matchAll(/--([\w-]+):\s*([^;]+);/g)];
  if (!declarations.length) throw new Error('Apell theme contains no tokens.');
  return declarations
    .map(([, name, value]) => {
      const scoped_value = value.replace(/var\(\s*--([\w-]+)/g, 'var(--apell-$1');
      return `  --apell-${name}: ${scoped_value};`;
    })
    .join('\n');
}
const css = source('src/styles.css');
const light = css.match(/^:root\s*\{([^}]+)\}/);
const dark = css.match(/@media\s*\(prefers-color-scheme:\s*dark\)\s*\{\s*:root\s*\{([^}]+)\}/);
if (!light || !dark) throw new Error('Apell theme structure changed; review the theme sync.');
const host_tokens = `/* Generated by bun run sync:theme from Apell ${revision}. */\n:root {\n${tokens(light[1])}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n${tokens(dark[1]).replace(/^/gm, '  ')}\n  }\n}\n`;
const shared_root = resolve(import.meta.dir, '../shared');
await writeFile(resolve(shared_root, 'host-tokens.css'), host_tokens);
console.log(`Synced platform theme from Apell ${revision.slice(0, 7)}.`);
